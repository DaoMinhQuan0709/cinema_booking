CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    full_name varchar(100) NOT NULL,
    phone varchar(20),
    role varchar(20) NOT NULL CHECK (role IN ('CUSTOMER', 'ADMIN')),
    created_at timestamp NOT NULL
);

CREATE TABLE movies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deleted_at timestamptz,
    deleted_by_user_id bigint,
    galaxy_movie_id varchar(100) CONSTRAINT uq_movies_galaxy_movie_id UNIQUE,
    galaxy_slug varchar(255),
    title varchar(255) NOT NULL,
    description text,
    duration_minutes integer NOT NULL,
    release_date date NOT NULL,
    poster_url varchar(500),
    landscape_url varchar(500),
    trailer_url varchar(500),
    genre varchar(500),
    country varchar(255),
    directors jsonb,
    actors jsonb,
    galaxy_details_synced_at timestamptz,
    galaxy_details_attempt_at timestamptz,
    age_rating varchar(10),
    status varchar(20) NOT NULL CHECK (status IN ('COMING_SOON', 'NOW_SHOWING', 'ENDED')),
    created_at timestamp NOT NULL
);
CREATE INDEX idx_movies_status ON movies (status);
CREATE INDEX idx_movies_release_date ON movies (release_date);

CREATE TABLE cinemas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    galaxy_cinema_id varchar(100) CONSTRAINT uq_cinemas_galaxy_cinema_id UNIQUE,
    site_id varchar(100),
    slug varchar(255),
    galaxy_city_id varchar(100),
    name varchar(255) NOT NULL,
    address text NOT NULL,
    city varchar(100) NOT NULL,
    latitude numeric(20,17),
    longitude numeric(20,17),
    phone varchar(50),
    image_landscape varchar(1000),
    image_portrait varchar(1000),
    image_urls jsonb,
    cinema_type varchar(50),
    display_order integer
);

CREATE TABLE auditoriums (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cinema_id bigint NOT NULL REFERENCES cinemas (id),
    name varchar(100) NOT NULL,
    total_rows integer NOT NULL,
    total_cols integer NOT NULL
);

CREATE TABLE seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auditorium_id bigint NOT NULL REFERENCES auditoriums (id),
    row_char varchar(5) NOT NULL,
    seat_number integer NOT NULL,
    type varchar(20) NOT NULL CHECK (type IN ('STANDARD', 'VIP', 'COUPLE')),
    is_active boolean NOT NULL,
    CONSTRAINT uk_seats_auditorium_row_col UNIQUE (auditorium_id, row_char, seat_number)
);

CREATE TABLE showtimes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deleted_at timestamptz,
    deleted_by_user_id bigint,
    galaxy_session_id varchar(100) CONSTRAINT uq_showtimes_galaxy_session_id UNIQUE,
    is_active boolean NOT NULL DEFAULT true,
    movie_id bigint NOT NULL REFERENCES movies (id),
    auditorium_id bigint NOT NULL REFERENCES auditoriums (id),
    start_time timestamp NOT NULL,
    end_time timestamp NOT NULL,
    base_price numeric(10,2) NOT NULL
);
CREATE INDEX idx_showtimes_movie_start ON showtimes (movie_id, start_time);
CREATE INDEX idx_showtimes_auditorium_start ON showtimes (auditorium_id, start_time);

CREATE TABLE showtime_seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    showtime_id bigint NOT NULL REFERENCES showtimes (id),
    seat_id bigint NOT NULL REFERENCES seats (id),
    price numeric(10,2) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('AVAILABLE', 'LOCKED', 'BOOKED')),
    locked_by_user_id bigint REFERENCES users (id),
    locked_until timestamp,
    lock_token varchar(64),
    version integer NOT NULL DEFAULT 0,
    CONSTRAINT uk_showtime_seats_showtime_seat UNIQUE (showtime_id, seat_id)
);
CREATE INDEX idx_showtime_seats_status ON showtime_seats (showtime_id, status);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    description text,
    price numeric(10,2) NOT NULL,
    image_url varchar(500),
    is_available boolean NOT NULL
);

CREATE TABLE bookings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code varchar(20) NOT NULL CONSTRAINT idx_bookings_booking_code UNIQUE,
    user_id bigint NOT NULL REFERENCES users (id),
    showtime_id bigint NOT NULL REFERENCES showtimes (id),
    total_amount numeric(12,2) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    qr_code_url varchar(500),
    created_at timestamp NOT NULL,
    expires_at timestamp NOT NULL,
    hold_token varchar(64)
);
CREATE INDEX idx_bookings_user_created ON bookings (user_id, created_at);
CREATE INDEX idx_bookings_status_expires ON bookings (status, expires_at);
CREATE INDEX idx_bookings_showtime_status ON bookings (showtime_id, status);

CREATE TABLE booking_seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES bookings (id),
    showtime_seat_id bigint NOT NULL REFERENCES showtime_seats (id),
    price numeric(10,2) NOT NULL,
    CONSTRAINT uk_booking_seats_booking_showtime_seat UNIQUE (booking_id, showtime_seat_id)
);

CREATE TABLE booking_products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES bookings (id),
    product_id bigint NOT NULL REFERENCES products (id),
    quantity integer NOT NULL,
    unit_price numeric(10,2) NOT NULL
);

CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL UNIQUE REFERENCES bookings (id),
    transaction_no varchar(100) UNIQUE,
    payment_method varchar(50) NOT NULL,
    amount numeric(12,2) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED', 'REFUND_REQUIRED')),
    paid_at timestamp
);

CREATE TABLE payment_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES bookings (id),
    method varchar(10) NOT NULL,
    revision varchar(64) NOT NULL,
    amount numeric(12,2) NOT NULL,
    provider_order_id varchar(100) NOT NULL UNIQUE,
    request_id varchar(64) NOT NULL UNIQUE,
    provider_transaction_id varchar(100),
    received_at timestamp,
    state varchar(20) NOT NULL CHECK (state IN ('EDITABLE', 'CREATING', 'READY', 'UNKNOWN', 'REJECTED', 'CLOSED')),
    outcome varchar(20) NOT NULL CHECK (outcome IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED', 'REFUND_REQUIRED')),
    payment_url text,
    created_at timestamp NOT NULL,
    lease_until timestamp NOT NULL,
    expires_at timestamp NOT NULL,
    version integer NOT NULL DEFAULT 0,
    CONSTRAINT uk_attempt_provider_transaction UNIQUE (method, provider_transaction_id)
);
CREATE INDEX idx_attempt_booking ON payment_attempts (booking_id, id);
CREATE UNIQUE INDEX uk_attempt_active_booking ON payment_attempts (booking_id)
    WHERE outcome = 'PENDING' AND state IN ('CREATING', 'READY', 'UNKNOWN');
