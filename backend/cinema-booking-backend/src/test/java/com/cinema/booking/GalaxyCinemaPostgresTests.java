package com.cinema.booking;

import com.cinema.booking.entity.Cinema;
import com.cinema.booking.repository.CinemaRepository;
import com.cinema.booking.service.CatalogGuard;
import com.cinema.booking.service.CinemaService;
import com.cinema.booking.service.impl.CinemaServiceImpl;
import com.cinema.booking.service.impl.GalaxyDataImporter;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.persistence.EntityManagerFactory;
import org.junit.jupiter.api.*;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.context.annotation.*;
import org.springframework.core.io.ClassPathResource;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.init.ScriptUtils;
import org.springframework.orm.jpa.*;
import org.springframework.orm.jpa.vendor.HibernateJpaVendorAdapter;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import org.springframework.transaction.support.TransactionTemplate;

import javax.sql.DataSource;
import java.math.BigDecimal;
import java.sql.*;
import java.util.*;

import static org.junit.jupiter.api.Assertions.*;

/** Upgrades a legacy cinema table and exercises real import/repository/JSONB mappings in an isolated schema. */
@EnabledIfEnvironmentVariable(named = "CINEMA_TEST_DB_URL", matches = ".+")
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class GalaxyCinemaPostgresTests {
    private static final String SCHEMA = "galaxy_cinema_test_" + UUID.randomUUID().toString().replace("-", "");
    private AnnotationConfigApplicationContext context;

    @Configuration
    @EnableTransactionManagement
    @EnableJpaRepositories(basePackageClasses = CinemaRepository.class)
    @Import({GalaxyDataImporter.class, CatalogGuard.class, CinemaServiceImpl.class})
    static class Config {
        @Bean
        DataSource dataSource() throws Exception {
            var ds = new DriverManagerDataSource(System.getenv("CINEMA_TEST_DB_URL"),
                    System.getenv("CINEMA_TEST_DB_USER"), System.getenv("CINEMA_TEST_DB_PASSWORD"));
            try (Connection connection = ds.getConnection()) {
                connection.createStatement().execute("CREATE SCHEMA " + SCHEMA);
            }
            ds.setSchema(SCHEMA);
            try (Connection connection = ds.getConnection(); Statement sql = connection.createStatement()) {
                sql.execute("CREATE TABLE movies (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, genre varchar(255))");
                sql.execute("CREATE TABLE showtimes (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
                sql.execute("CREATE TABLE cinemas (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                        + "name varchar(255) NOT NULL, address text NOT NULL, city varchar(100) NOT NULL)");
                sql.execute("INSERT INTO cinemas (name, address, city) VALUES ('Legacy Galaxy', 'Old address', 'Hà Nội')");
                var script = new ClassPathResource("db/manual/galaxy-sync.sql");
                ScriptUtils.executeSqlScript(connection, script);
                ScriptUtils.executeSqlScript(connection, script);
                // Check the migration before Hibernate can add any columns itself.
                try (ResultSet row = sql.executeQuery("SELECT id, name, site_id, slug, galaxy_city_id, latitude, longitude, "
                        + "phone, image_landscape, image_portrait, image_urls, cinema_type, display_order FROM cinemas")) {
                    assertTrue(row.next());
                    assertEquals(1L, row.getLong("id"));
                    assertEquals("Legacy Galaxy", row.getString("name"));
                    assertNull(row.getString("site_id"));
                }
            }
            return ds;
        }

        @Bean
        LocalContainerEntityManagerFactoryBean entityManagerFactory(DataSource ds) {
            var factory = new LocalContainerEntityManagerFactoryBean();
            factory.setDataSource(ds);
            factory.setPackagesToScan("com.cinema.booking.entity");
            factory.setJpaVendorAdapter(new HibernateJpaVendorAdapter());
            factory.setJpaPropertyMap(Map.of("hibernate.hbm2ddl.auto", "update", "hibernate.default_schema", SCHEMA));
            return factory;
        }

        @Bean
        PlatformTransactionManager transactionManager(EntityManagerFactory factory) {
            return new JpaTransactionManager(factory);
        }

        @Bean
        TransactionTemplate transactionTemplate(PlatformTransactionManager manager) {
            return new TransactionTemplate(manager);
        }
    }

    @BeforeAll
    void start() {
        context = new AnnotationConfigApplicationContext(Config.class);
    }

    @AfterAll
    void close() throws Exception {
        if (context != null) context.close();
        if (!SCHEMA.matches("galaxy_cinema_test_[a-f0-9]{32}")) throw new IllegalStateException("Unexpected schema");
        try (Connection connection = DriverManager.getConnection(System.getenv("CINEMA_TEST_DB_URL"),
                System.getenv("CINEMA_TEST_DB_USER"), System.getenv("CINEMA_TEST_DB_PASSWORD"))) {
            connection.createStatement().execute("DROP SCHEMA IF EXISTS " + SCHEMA + " CASCADE");
        }
    }

    @Test
    void migratedCinemaKeepsItsIdAndRoundTripsMetadataAndEmptyGallery() throws Exception {
        var mapper = new ObjectMapper();
        var empty = mapper.createArrayNode();
        var catalog = mapper.createArrayNode();
        var source = catalog.addObject().put("id", "galaxy-cinema-1").put("name", "Legacy Galaxy")
                .put("siteId", "000001029").put("slug", "galaxy-legacy").put("address", "175 Nguyễn Thái Học, Hà Nội")
                .put("cityId", "f4bf5f53-4e80-40c8-b1e0-f11ffa9a636a").put("latitude", "21.031587302213463")
                .put("longitude", "105.8309551052807").put("phone", "19002224")
                .put("imageLandscape", "https://cdn.example/landscape.jpg")
                .put("imagePortrait", "https://cdn.example/portrait.jpg").put("cinemaType", "premium").put("order", 0);
        source.putArray("imageUrls").add("https://cdn.example/rạp-1.jpg").add("https://cdn.example/rạp-2.jpg");
        var importer = context.getBean(GalaxyDataImporter.class);
        importer.importData(empty, empty, empty, catalog, 0, true);
        importer.importData(empty, empty, empty, catalog, 0, true);
        var tx = context.getBean(TransactionTemplate.class);
        Cinema cinema = tx.execute(status -> context.getBean(CinemaRepository.class).findByGalaxyCinemaId("galaxy-cinema-1").orElseThrow());
        assertNotNull(cinema);
        assertEquals(1L, cinema.getId());
        assertEquals("000001029", cinema.getSiteId());
        assertEquals(0, new BigDecimal("21.031587302213463").compareTo(cinema.getLatitude()));
        assertEquals(0, new BigDecimal("105.8309551052807").compareTo(cinema.getLongitude()));
        assertEquals(List.of("https://cdn.example/rạp-1.jpg", "https://cdn.example/rạp-2.jpg"), cinema.getImageUrls());
        var response = context.getBean(CinemaService.class).getCinemaById(1L);
        assertEquals("premium", response.getCinemaType());
        assertEquals(2, response.getImageUrls().size());
        assertTrue(response.getAuditoriums().isEmpty());
        source.putArray("imageUrls");
        importer.importData(empty, empty, empty, catalog, 0, true);
        assertTrue(context.getBean(CinemaService.class).getCinemaById(1L).getImageUrls().isEmpty());
        assertEquals(1L, context.getBean(CinemaRepository.class).count());
    }
}
