-- Run with the application schema selected. Safe to repeat; keeps legacy payment rows.
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS hold_token varchar(64);
ALTER TABLE showtime_seats ADD COLUMN IF NOT EXISTS lock_token varchar(64);

CREATE TABLE IF NOT EXISTS payment_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES bookings(id),
    method varchar(10) NOT NULL,
    revision varchar(64) NOT NULL,
    amount numeric(12,2) NOT NULL,
    provider_order_id varchar(100) NOT NULL UNIQUE,
    request_id varchar(64) NOT NULL UNIQUE,
    state varchar(20) NOT NULL,
    outcome varchar(20) NOT NULL,
    payment_url text,
    created_at timestamp NOT NULL,
    lease_until timestamp NOT NULL,
    expires_at timestamp NOT NULL,
    version integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_attempt_booking ON payment_attempts(booking_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_attempt_active_booking ON payment_attempts(booking_id)
    WHERE outcome = 'PENDING' AND state IN ('CREATING', 'READY', 'UNKNOWN');
